"""Print the Tithi / Karana / Yoga source crosswalk (KUN-PAN-M2-NAMES-001) as Markdown.

    python report/phase1/tools/panchanga_names_crosswalk.py > docs/i18n/PANCHANGA-NAMES-CROSSWALK.md

Built only from report/phase1/panchanga_names.json and research/panchanga/names/imd-names-evidence.json,
so the committed document can be checked for drift by the tests. Nothing is computed by the engine.
"""
from __future__ import annotations

import json
import sys
from datetime import datetime, timedelta, timezone
from pathlib import Path

REPO = Path(__file__).resolve().parents[3]
sys.path.insert(0, str(REPO))
from report.phase1 import panchanga_names as pn  # noqa: E402

EVIDENCE = json.loads((REPO / 'research/panchanga/names/imd-names-evidence.json').read_text(encoding='utf-8'))


def observed():
    """{element: {index: [date, ...]}} where the IMD Kartika 1948 daily pages print that slot."""
    names = EVIDENCE['names_page']['tithi']
    day_of = {v: int(k) for k, v in names.items()}
    out = {'tithi': {}, 'karana': {}, 'yoga': {}}
    ist = timezone(timedelta(hours=5, minutes=30))

    def end(date, clock):
        h, m = (int(x) for x in clock.split('-'))
        return datetime.fromisoformat(date).replace(tzinfo=ist) + timedelta(hours=h, minutes=m)
    tithi_ends = {}
    for row in EVIDENCE['daily_kartika_1948']['rows']:
        for paksha, printed, clock in row['tithi']:
            d = day_of[printed]
            n = d if d in (15, 30) else d + (15 if paksha.endswith('Krishna') else 0)
            out['tithi'].setdefault(n, []).append(row['date'])
            if clock != 'ahoratra':
                tithi_ends[end(row['date'], clock)] = n
        for printed, _ in row['yoga']:
            i = next(i for i in range(1, 28) if printed in
                     [pn.source_spelling('yoga', i)] + pn.CATALOG['terms'][pn.term_id('yoga', i)]['source_spelling']['alternates'])
            out['yoga'].setdefault(i, []).append(row['date'])
    karanas = [(row['date'], printed, end(row['date'], clock))
               for row in EVIDENCE['daily_kartika_1948']['rows'] for printed, clock in row['karana']]
    anchor = next(i for i, k in enumerate(karanas) if k[2] in tithi_ends)
    first = 2 * tithi_ends[karanas[anchor][2]] - anchor
    for offset, (date, _, _) in enumerate(karanas):
        out['karana'].setdefault((first + offset - 1) % 60 + 1, []).append(date)
    return out


def main():
    seen = observed()
    c = pn.CATALOG
    lines = ['# Panchanga names: source crosswalk (KUN-PAN-M2-NAMES-001)', '',
             '**Status:** mappings source-checked against IMD; English and Hindi display forms are developer '
             'proposals PENDING human Hindi language and Jyotish terminology review. Not customer-facing. '
             'Generated by `report/phase1/tools/panchanga_names_crosswalk.py`; do not edit by hand.', '',
             'Sources (accessed 2026-11-06, Positional Astronomy Centre, India Meteorological Department):', '']
    for key, s in EVIDENCE['sources'].items():
        lines.append(f"- **{key}**: <{s['url']}> ({s.get('section_heading', s.get('edition', ''))})")
    lines += ['', 'Columns: index; machine id; IMD spelling as printed (alternates seen on daily pages); proposed '
              'English; proposed Hindi; evidence. *Rule* = names page order plus the explanation page rule; '
              '*Daily* = the dates on the IMD Kartika 1948 daily pages where that exact slot is printed.', '']
    lines += ['## Tithi (30)', '', '| # | Paksha | Machine id | IMD spelling | English (proposed) | Hindi (proposed) | Evidence |',
              '|---|---|---|---|---|---|---|']
    for n in range(1, 31):
        e = c['tithi'][str(n)]
        t = c['terms'][e['name']]
        dates = ', '.join(d[5:] for d in seen['tithi'].get(n, [])) or 'not in the month read'
        lines.append(f"| {n} | {e['paksha']} {e['paksha_day']} | `{e['name']}` | {t['source_spelling']['text']} | "
                     f"{pn.tithi_label(n, 'en')} | {pn.tithi_label(n, 'hi')} | Names page; Daily {dates} |")
    lines += ['', '## Karana (60)', '', '| # | Half | Machine id | Kind | IMD spelling | English (proposed) | Hindi (proposed) | Evidence |',
              '|---|---|---|---|---|---|---|---|']
    for i in range(1, 61):
        t = c['terms'][pn.term_id('karana', i)]
        tithi = (i + 1) // 2
        half = f"Tithi {tithi} {'1st' if i % 2 else '2nd'}"
        alt = t['source_spelling']['alternates']
        spelling = t['source_spelling']['text'] + (f" ({', '.join(alt)})" if alt else '')
        dates = ', '.join(d[5:] for d in seen['karana'].get(i, []))
        lines.append(f"| {i} | {half} | `{t['id']}` | {t['karana_kind']} | {spelling} | {t['display']['en']} | "
                     f"{t['display']['hi']} | Rule; Daily {dates} |")
    lines += ['', '## Panchanga Yoga (27; not a planetary Yoga)', '',
              '| # | S from | Machine id | IMD spelling | English (proposed) | Hindi (proposed) | Evidence |',
              '|---|---|---|---|---|---|---|']
    for i in range(1, 28):
        t = c['terms'][pn.term_id('yoga', i)]
        alt = t['source_spelling']['alternates']
        spelling = t['source_spelling']['text'] + (f" ({', '.join(alt)})" if alt else '')
        start = (i - 1) * 800
        dates = ', '.join(d[5:] for d in seen['yoga'].get(i, []))
        lines.append(f"| {i} | {start // 60}°{start % 60:02d}′ | `{t['id']}` | {spelling} | {t['display']['en']} | "
                     f"{t['display']['hi']} | Names page order; Daily {dates} |")
    lines += ['', '## Coverage', '',
              f"- Tithi slots printed in the month read: {len(seen['tithi'])} of 30.",
              f"- Karana slots printed in the month read: {len(seen['karana'])} of 60.",
              f"- Yoga slots printed in the month read: {len(seen['yoga'])} of 27.", '']
    print('\n'.join(lines))


if __name__ == '__main__':
    main()
